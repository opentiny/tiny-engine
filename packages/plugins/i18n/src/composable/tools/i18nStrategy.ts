/**
 * i18n 工具使用策略 Prompt
 * 定义在 TinyEngine 低代码应用中处理国际化的首选策略
 */
export const i18nStrategyPrompt = () => {
  return `
# TinyEngine i18n 工具使用策略

当在 TinyEngine 低代码应用中处理国际化(i18n)内容时，请遵循以下策略和最佳实践：

## 1. 工具概览与用途

### 可用工具：
- **get_i18n (getI18n)**: 获取现有的国际化条目
- **add_i18n**: 添加新的国际化条目
- **update_i18n**: 更新现有的国际化条目
- **delete_i18n**: 删除国际化条目

## 2. 工作流程指导

### 2.1 开始任何 i18n 操作前
**必须首先使用 get_i18n 检查现有条目：**
- 不带参数调用 \`get_i18n()\` 获取所有条目概览
- 带特定 key 调用 \`get_i18n(key: "specific.key")\` 检查特定条目是否存在

### 2.2 添加新的国际化条目
**使用 add_i18n 时：**
- **Key 命名规范**: 使用点分隔的层级结构，如 \`lowcode.component.button.text\`
- **Key 前缀建议**:
  - \`lowcode.*\` - 低代码平台相关
  - \`component.*\` - 组件相关文本
  - \`message.*\` - 消息提示类
  - \`label.*\` - 标签类文本
  - \`button.*\` - 按钮文本
  - \`form.*\` - 表单相关
- **翻译内容要求**:
  - zh_CN: 提供准确的中文翻译
  - en_US: 提供准确的英文翻译
  - 保持语义一致性和上下文适配

### 2.3 更新现有条目
**使用 update_i18n 时：**
- 先用 get_i18n 获取现有内容，了解当前翻译
- 只更新需要修改的语言版本
- 保持其他语言版本的一致性

### 2.4 删除条目
**使用 delete_i18n 时：**
- 谨慎操作，先确认该 key 不被其他地方引用
- 考虑是否应该更新而非删除

## 3. Key 命名最佳实践

### 3.1 命名规则
- 使用小写字母和数字
- 用点(.)分隔层级
- 用下划线(_)分隔单词
- 避免使用特殊字符和空格

### 3.2 推荐的层级结构
\`\`\`
[domain].[module].[component].[element].[property]
\`\`\`

**示例：**
- \`lowcode.designer.toolbar.save.text\` - 设计器工具栏保存按钮文本
- \`lowcode.property.panel.title\` - 属性面板标题
- \`component.table.empty.description\` - 表格空状态描述
- \`message.save.success\` - 保存成功消息
- \`form.validation.required\` - 表单必填验证消息

## 4. 翻译内容指导

### 4.1 中文翻译 (zh_CN)
- 使用简体中文
- 语言简洁明了，符合中文表达习惯
- 专业术语使用行业标准翻译
- 保持语气一致性（正式/非正式）

### 4.2 英文翻译 (en_US)
- 使用美式英语拼写
- 语法正确，表达自然
- 首字母大小写遵循 UI 规范
- 避免过于复杂的句式

### 4.3 一致性原则
- 相同概念在不同位置使用相同翻译
- 保持术语的统一性
- 维护品牌和产品名称的一致性

## 5. 错误处理和验证

### 5.1 常见错误避免
- 添加前检查 key 是否已存在
- 更新前确认目标 key 存在
- 删除前评估影响范围
- 确保提供的翻译内容不为空

### 5.2 验证检查
- Key 格式符合规范
- 翻译内容完整且有意义
- 没有重复的 key
- 翻译内容长度适中

## 6. 批量操作建议

### 6.1 批量添加
- 使用一致的命名前缀
- 保持相关条目的逻辑分组
- 考虑条目之间的关联性

### 6.2 批量更新
- 先备份现有内容（通过 get_i18n 获取）
- 逐个验证更新结果
- 保持操作的原子性

## 7. 特殊场景处理

### 7.1 动态内容处理
- 对于包含变量的文本，使用占位符如 \`{name}\` 或 \`{count}\`
- 在 key 中体现动态特性，如 \`message.welcome.user\`

### 7.2 复数形式处理
- 英文复数可使用不同 key，如 \`item\` 和 \`items\`
- 中文通常不需要复数形式区分

### 7.3 上下文相关翻译
- 相同词汇在不同上下文的翻译可能不同
- Key 命名应体现具体使用场景

## 8. 优先级策略

**操作优先级顺序：**
1. 首先查询现有内容 (get_i18n)
2. 评估是否需要新增、更新或删除
3. 选择合适的工具执行操作
4. 验证操作结果

**Key 冲突处理：**
- 发现 key 已存在时，考虑是否应该更新而非重复添加
- 如果确实需要新 key，调整命名以避免冲突

遵循这些策略将确保 TinyEngine 应用的国际化内容管理规范、一致且高效。
`
}

